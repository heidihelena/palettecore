"""Digital rain — palette generator + audit for the falling-code art piece.

Forty-eight notes, C2..B5, on the same pitch-colour helix as the other
experiments (angle = pitch class on a closed CIEDE2000-spaced hue ring,
height = lightness = absolute pitch). Each column of rain carries one note;
the note's colour is the colour of every glyph in that column, and the note
sounds when the drop reaches the bottom of the screen.

The piece is the full chromatic mapping on purpose, and the audit splits:
in normal vision the 48 colours clear the package's exploratory dE 6 design
floor (minimum adjacent 7.1, none below the floor), because lightness climbs
with absolute pitch and does most of the separating work over four octaves.
Under all three simulated dichromacies it collapses — minimum adjacent falls
to 0.9-1.8, roughly half of the 47 steps drop below the floor, and protanopia
adds nine local luminance reversals, so the "higher note is lighter" claim
breaks too. The honest claim for this piece is therefore: art built on the
mapping, readable as a code only in normal vision, and never an accessible
encoding. digital_rain.html carries the vision toggles so a visitor can watch
the collapse rather than take it on trust. The ladder that survives
dichromacy is the four-class one in waves_to_shore.py.

Writes output/digital_rain.json and injects the palette + Machado matrices
into all three HTML builds between generated-code markers, so no artwork can
drift from the engine.

Run:  PYTHONPATH=.:experiments python3 experiments/digital_rain.py
"""

from __future__ import annotations

import json
import pathlib

import numpy as np

from palettecore.convert import hex_to_srgb
from palettecore.cvd import CONDITIONS, MACHADO_10, simulate_cvd
from palettecore.metrics import ciede2000, relative_luminance
from pitch_color_helix import helix

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "output"
HTML = [HERE / n for n in ("digital_rain.html",
                           "digital_rain_ambient.html",
                           "digital_rain_live.html",
                           "digital_rain_dome.html")]
FLOOR = 6.0
N_LOW, N_HIGH = -24, 23          # C2 .. B5, the 48 notes of the poem


def ladder48():
    """C2..B5 on the helix, in the order the piece introduces them."""
    return [{k: p[k] for k in ("note", "pc", "f", "L", "hue", "hex")}
            for p in helix(n_low=N_LOW, n_high=N_HIGH)]


def audit(entries):
    """Adjacent + full-pairwise minimum dE per vision condition.

    Adjacent order is chromatic, which is the order the rain introduces the
    notes and the order a viewer would try to read the code in. The pairwise
    minimum is the claim that binds when two arbitrary columns fall side by
    side, which is what actually happens. Minima, never means.
    """
    rgbs = [hex_to_srgb(e["hex"]) for e in entries]
    res = {}
    for cond in (None, *CONDITIONS):
        key = cond or "normal"
        cols = [simulate_cvd(c, cond) if cond else c for c in rgbs]
        adj = [ciede2000(cols[i], cols[i + 1]) for i in range(len(cols) - 1)]
        i_worst = int(np.argmin(adj))
        pair = min(ciede2000(cols[i], cols[j])
                   for i in range(len(cols)) for j in range(i + 1, len(cols)))
        # Lightness carries absolute pitch, so a local luminance reversal is a
        # broken claim even where the colours stay far apart. Count them.
        lum = [relative_luminance(c) for c in cols]
        rev = sum(1 for i in range(len(lum) - 1) if lum[i + 1] <= lum[i])
        res[key] = {
            "adjacent_min": round(float(np.min(adj)), 1),
            "adjacent_below_floor": int(np.sum(np.array(adj) < FLOOR)),
            "adjacent_steps": len(adj),
            "worst_adjacent": f"{entries[i_worst]['note']}->{entries[i_worst + 1]['note']}",
            "pairwise_min": round(float(pair), 1),
            "luminance_reversals": rev,
        }
    return res


def inject(html_path, payload):
    """Replace the generated block in the HTML with fresh data."""
    begin = "// BEGIN GENERATED by digital_rain.py — do not edit by hand"
    end = "// END GENERATED"
    text = html_path.read_text()
    i, j = text.index(begin), text.index(end)
    block = f"{begin}\nconst DATA = {json.dumps(payload, indent=1)};\n"
    html_path.write_text(text[:i] + block + text[j:])


def main():
    OUT.mkdir(exist_ok=True)
    notes = ladder48()
    result = {
        "model": "pitch-colour helix (angle = pitch class on a closed dE-spaced "
                 "hue ring, height = lightness = absolute pitch), audited on the "
                 "exact colours the artwork displays",
        "floor": FLOOR,
        "range": "C2..B5, 48 chromatic notes",
        "claim": "art built on the mapping, not an accessible encoding: the "
                 "48 colours clear the exploratory floor in normal vision, and "
                 "collapse under every simulated dichromacy",
        "notes": notes,
        "audit": audit(notes),
    }
    (OUT / "digital_rain.json").write_text(json.dumps(result, indent=2))

    payload = {
        "notes": notes,
        "audit": result["audit"],
        "machado": {k: [[round(float(v), 6) for v in row] for row in m]
                    for k, m in MACHADO_10.items()},
    }
    for path in HTML:
        if path.exists():
            inject(path, payload)

    print(f"digital rain — {len(notes)} notes, "
          f"{notes[0]['note']}..{notes[-1]['note']} (floor {FLOOR}):")
    print(f"  {'vision':13s} {'adj min':>8s} {'adj <6':>9s} {'pair min':>9s} "
          f"{'lum rev':>8s}  worst adjacent")
    for k, s in result["audit"].items():
        print(f"  {k:13s} {s['adjacent_min']:8.1f} "
              f"{s['adjacent_below_floor']:4d}/{s['adjacent_steps']:<4d} "
              f"{s['pairwise_min']:9.1f} {s['luminance_reversals']:8d}  "
              f"{s['worst_adjacent']}")
    print(f"\nwrote {OUT / 'digital_rain.json'}")
    for path in HTML:
        print(f"updated generated palette block in {path.name}"
              if path.exists() else f"skipped (missing) {path.name}")


if __name__ == "__main__":
    main()
