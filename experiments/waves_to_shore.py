"""Waves to the shore — palette generator + audit for the art piece.

Derives the colours used by waves_to_shore.html from the same pitch-colour
helix model as the other experiments (angle = pitch class on a closed
CIEDE2000-spaced hue ring, height = lightness = absolute pitch), audits them
under the three Machado dichromacy simulations, writes the machine-readable
result to output/waves_to_shore.json, and injects the palette + Machado
matrices into the HTML between generated-code markers so the artwork can
never drift from the engine.

Two ladders ship with the piece:

- ladder4  — 4 pitch classes per octave (C, D, G, A) over C3..C6. Four hues
  per octave is the resolution the frontier sweep found to clear the package's
  exploratory dE 6 design floor in all three simulations; the sounding pitches
  here are a musical choice (a suspended/pentatonic-flavoured set rather than
  equal divisions), lightness still climbs with absolute semitone index, and
  the audit below is computed on these exact colours, not inherited from the
  sweep.
- ladder12 — the full chromatic helix (C3..C6) from pitch_color_helix.py,
  included so the piece can show what the audit shows: under simulated CVD
  the 12-tone mapping collapses.

Run:  PYTHONPATH=.:experiments python3 experiments/waves_to_shore.py
"""

from __future__ import annotations

import json
import pathlib

import numpy as np

from palettecore.convert import hex_to_srgb, srgb_to_hex
from palettecore.cvd import CONDITIONS, MACHADO_10, simulate_cvd
from palettecore.metrics import ciede2000
from pitch_color_frontier import _max_chroma, _rgb, _safe_chroma, closed_ring_hues
from pitch_color_helix import helix

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "output"
HTML = HERE / "waves_to_shore.html"
FLOOR = 6.0
F_C4 = 261.626
NOTE = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]

# The four sounding pitch classes and their semitone offsets from C.
LADDER4_OFFSETS = (("C", 0), ("D", 2), ("G", 7), ("A", 9))


def ladder4(n_octaves=3, span=36, L_lo=0.30, L_hi=0.92):
    """C-D-G-A over C3..C6, closed by the final C6.

    Hue = one of 4 CIEDE2000-spaced angles by pitch class; lightness climbs
    with absolute semitone index (log frequency), exactly the helix model.
    """
    hues = closed_ring_hues(4)
    steps = [(name, 12 * octave + off, k)
             for octave in range(n_octaves)
             for k, (name, off) in enumerate(LADDER4_OFFSETS)]
    steps.append(("C", 12 * n_octaves, 0))
    out = []
    for name, n, k in steps:
        L = L_lo + (L_hi - L_lo) * n / span
        H = hues[k]
        C = min(_safe_chroma(round(L, 3)), _max_chroma(round(L, 3), round(H, 1)))
        octave = 3 + n // 12
        out.append({"note": f"{name}{octave}", "pc": name,
                    "f": round(F_C4 * 2 ** ((n - 12) / 12), 2),
                    "L": round(L, 3), "hue": round(float(H), 1),
                    "hex": srgb_to_hex(_rgb(L, C, H))})
    return out


def audit(entries):
    """Adjacent + full-pairwise minimum dE per vision condition.

    Adjacent order is the ladder order (the note walk in the piece moves
    mostly to neighbours); the pairwise minimum is the claim that binds for
    arbitrary leaps. Reported as minima, never means.
    """
    rgbs = [hex_to_srgb(e["hex"]) for e in entries]
    res = {}
    for cond in (None, *CONDITIONS):
        key = cond or "normal"
        cols = [simulate_cvd(c, cond) if cond else c for c in rgbs]
        adj = [ciede2000(cols[i], cols[i + 1]) for i in range(len(cols) - 1)]
        i_worst = int(np.argmin(adj))
        pair = min(ciede2000(cols[i], cols[j])
                   for i in range(len(cols)) for j in range(i + 1, len(cols)))
        res[key] = {
            "adjacent_min": round(float(np.min(adj)), 1),
            "adjacent_below_floor": int(np.sum(np.array(adj) < FLOOR)),
            "adjacent_steps": len(adj),
            "worst_adjacent": f"{entries[i_worst]['note']}->{entries[i_worst + 1]['note']}",
            "pairwise_min": round(float(pair), 1),
        }
    return res


def inject(html_path, payload):
    """Replace the generated block in the HTML with fresh data."""
    begin = "// BEGIN GENERATED by waves_to_shore.py — do not edit by hand"
    end = "// END GENERATED"
    text = html_path.read_text()
    i, j = text.index(begin), text.index(end)
    block = f"{begin}\nconst DATA = {json.dumps(payload, indent=1)};\n"
    html_path.write_text(text[:i] + block + text[j:])


def main():
    OUT.mkdir(exist_ok=True)
    l4 = ladder4()
    l12 = [{k: p[k] for k in ("note", "pc", "f", "L", "hue", "hex")} for p in helix()]

    result = {
        "model": "pitch-colour helix (angle = pitch class on a closed dE-spaced "
                 "hue ring, height = lightness = absolute pitch), audited on the "
                 "exact colours the artwork displays",
        "floor": FLOOR,
        "ladder4": l4,
        "ladder12": l12,
        "audit": {"ladder4": audit(l4), "ladder12": audit(l12)},
    }
    (OUT / "waves_to_shore.json").write_text(json.dumps(result, indent=2))

    payload = {
        "ladder4": l4,
        "ladder12": l12,
        "audit": result["audit"],
        "machado": {k: [[round(float(v), 6) for v in row] for row in m]
                    for k, m in MACHADO_10.items()},
    }
    inject(HTML, payload)

    for name, aud in result["audit"].items():
        print(f"\n{name} — minimum dE per vision (floor {FLOOR}):")
        print(f"  {'vision':13s} {'adj min':>8s} {'adj <6':>7s} {'pair min':>9s}  worst adjacent")
        for k, s in aud.items():
            print(f"  {k:13s} {s['adjacent_min']:8.1f} "
                  f"{s['adjacent_below_floor']:3d}/{s['adjacent_steps']:<3d} "
                  f"{s['pairwise_min']:9.1f}  {s['worst_adjacent']}")
    print(f"\nwrote {OUT / 'waves_to_shore.json'}")
    print(f"updated generated palette block in {HTML.name}")


if __name__ == "__main__":
    main()
